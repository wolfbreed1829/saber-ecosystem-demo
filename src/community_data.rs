use serde::Deserialize;
use std::sync::LazyLock;

#[derive(Clone, Deserialize, PartialEq)]
pub struct Place {
    pub id: String,
    pub name: String,
    pub group: String,
    pub icon: String,
    pub tagline: String,
    pub description: String,
    pub spaces: Vec<String>,
    pub routine: Vec<String>,
    pub people: String,
    pub continuity: String,
    pub domains: Vec<String>,
}
pub static PLACES: LazyLock<Vec<Place>> = LazyLock::new(|| {
    serde_json::from_str(include_str!("places.json")).expect("valid place content")
});
pub fn place(id: &str) -> Option<&'static Place> {
    PLACES.iter().find(|p| p.id == id)
}

